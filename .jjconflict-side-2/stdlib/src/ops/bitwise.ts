export const shl = ($_this: number, other: number) => $_this << other;
export const shr = ($_this: number, other: number) => $_this >> other;
export const bit_and = ($_this: number, other: number) => $_this & other;
export const bit_or = ($_this: number, other: number) => $_this | other;
export const bit_xor = ($_this: number, other: number) => $_this ^ other;
export const bit_not = ($_this: number) => ~$_this;
